const {chromium}=require('./browser.cjs');
const path=require('path');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({...require('./browser.cjs').launchOptions,headless:true});
 const page=await browser.newPage({viewport:{width:1120,height:860}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const state={mode:'idle',id:'host',name:'Windows test',running:false,error:'',code:'',addresses:['192.168.1.2'],devices:[{id:'source',name:'扬声器（回采源）',input:true,output:true},{id:'headphones',name:'耳机',input:true,output:true}],audioStatus:'未开始音频',logs:[],room:{}};
 const commands=[];
 await page.addInitScript(s=>{window.__state=s;window.__commands=[];window.AudioHubNative={state:()=>JSON.stringify(window.__state),command:f=>window.__commands.push(f),copy:()=>{}};},state);
 await page.goto('file:///'+path.resolve(__dirname,'../src/ui/index.html').replace(/\\/g,'/'));
 await page.waitForTimeout(900);
 await page.screenshot({path:path.join(__dirname,'../build/ui/ui-overview-desktop.png')});
 await page.getByRole('button',{name:'局域网',exact:true}).click();
 await page.screenshot({path:path.join(__dirname,'../build/ui/ui-lan-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'创建房间',exact:true}).click();
 if(!(await page.evaluate(()=>window.__commands)).some(c=>c.includes('action=host')))throw Error('host command missing');
 await page.evaluate(()=>{window.__state.mode='host';window.__state.running=true;window.__state.localSend=true;window.__state.localSource='source';window.__state.localOutputs=['耳机0'];window.__state.room={center:'host',centerName:'中心电脑',inputs:5,outputs:5,members:Array.from({length:5},(_,i)=>({id:i?'member'+i:'host',name:i?'设备'+i:'中心电脑',send:true,source:i?'media':'source',devices:i?[{id:'media',name:'媒体声音',input:true}]:[],ready:true,outputs:['耳机'+i],gain:1,peak:.2}))};});
 await page.waitForTimeout(900);
 if(await page.locator('#inputGains .gain').count()!==5)throw Error('five inputs not rendered');
 await page.getByRole('button',{name:'总览',exact:true}).click();await page.waitForTimeout(100);
 if(await page.locator('#arrows g path').count()<10)throw Error('topology arrows missing');
 await page.screenshot({path:path.join(__dirname,'../build/ui/ui-topology-five.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(__dirname,'../build/ui/ui-overview-mobile.png'),fullPage:true});
 await page.getByRole('button',{name:'局域网',exact:true}).click();await page.screenshot({path:path.join(__dirname,'../build/ui/ui-lan-mobile.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('mobile page overflow');
 await page.getByRole('button',{name:'设置',exact:true}).click();await page.screenshot({path:path.join(__dirname,'../build/ui/ui-settings-mobile.png'),fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS desktop/mobile layout, five inputs/outputs, ten topology arrows, host command, no JS errors or body overflow');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
